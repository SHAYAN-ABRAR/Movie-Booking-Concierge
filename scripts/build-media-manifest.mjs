#!/usr/bin/env node
/**
 * One-off authoring tool. Generates `src/data/mediaManifest.ts` — the
 * attribution record for every image file shipped in this repository.
 *
 *   node scripts/build-media-manifest.mjs
 */

import { readFileSync, writeFileSync } from 'node:fs';

const images = JSON.parse(readFileSync('movie-images.json', 'utf8'));
const moviesSource = readFileSync('src/data/movies.ts', 'utf8');

const esc = (s) => String(s).replace(/\\/g, '\\\\').replace(/'/g, "\\'");

const rows = images.map((entry) => {
  const id = moviesSource.match(new RegExp(`id: '(mov-${entry.slug})'`))?.[1];
  if (!id) throw new Error(`no movie id for slug "${entry.slug}"`);
  return { ...entry, movieId: id };
});

const body = rows
  .map(
    (r) => `  {
    movieId: '${r.movieId}',
    movieTitle: '${esc(r.movie)}',
    role: '${r.role}',
    basePath: '${r.basePath}',
    widths: [${r.widths.join(', ')}],
    alt: '${esc(
      r.role === 'poster'
        ? `Theatrical poster for ${r.movie}`
        : `Still from ${r.movie}`,
    )}',
    focalPoint: '${r.role === 'poster' ? 'center' : '50% 40%'}',
    source: '${r.source}',
    sourcePage: '${r.sourcePage}',
    provider: 'TMDB',
    licence: 'TMDB terms of use — attribution required, no endorsement implied',
    originalDimensions: '${r.originalWidth}×${r.originalHeight}',
    processedDimensions: '${r.processedWidth}×${r.processedHeight}',
    verifiedAt: '2026-08-03',
  },`,
  )
  .join('\n');

const file = `/**
 * Media attribution.
 *
 * Every image file in \`public/media/movies/\` is recorded here: where it came
 * from, what licence it is used under, its original and processed dimensions,
 * and the alt text the interface must use for it.
 *
 * The images were downloaded **once** at authoring time by
 * \`scripts/fetch-movie-images.mjs\` and committed to this repository. The
 * running application never requests an image from a remote host, and needs no
 * API key of any kind.
 *
 * **This product uses the TMDB API but is not endorsed or certified by TMDB.**
 *
 * Generated by \`scripts/build-media-manifest.mjs\`.
 */

export interface MediaAsset {
  movieId: string;
  movieTitle: string;
  role: 'poster' | 'backdrop';
  /** Local path without width or extension. */
  basePath: string;
  /** Rendered widths available on disk, ascending. */
  widths: number[];
  alt: string;
  /** CSS \`object-position\` for crops. */
  focalPoint: string;
  source: string;
  sourcePage: string;
  provider: string;
  licence: string;
  originalDimensions: string;
  processedDimensions: string;
  verifiedAt: string;
}

export const mediaManifest: MediaAsset[] = [
${body}
];

export const mediaByMovie = new Map<string, { poster?: MediaAsset; backdrop?: MediaAsset }>();
for (const asset of mediaManifest) {
  const entry = mediaByMovie.get(asset.movieId) ?? {};
  entry[asset.role] = asset;
  mediaByMovie.set(asset.movieId, entry);
}

/** The attribution line the About page is required to show. */
export const TMDB_ATTRIBUTION =
  'This product uses the TMDB API but is not endorsed or certified by TMDB.';
`;

writeFileSync('src/data/mediaManifest.ts', file);
console.log(`wrote src/data/mediaManifest.ts (${rows.length} assets)`);
