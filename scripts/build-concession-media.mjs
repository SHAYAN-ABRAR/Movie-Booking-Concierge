#!/usr/bin/env node
/**
 * One-off authoring tool. Writes `src/data/concessionMedia.ts` and
 * `docs/concession-image-sources.md` from `concession-photos.json`.
 */

import { readFileSync, writeFileSync } from 'node:fs';

const photos = JSON.parse(readFileSync('concession-photos.json', 'utf8'));
const esc = (s) => String(s ?? '').replace(/\\/g, '\\\\').replace(/'/g, "\\'");

/** Alt text is written by hand — a caption, not a filename. */
const ALT = {
  'con-popcorn-salt-r': 'A carton of freshly popped salted popcorn',
  'con-popcorn-salt-l': 'A large tub of popcorn',
  'con-popcorn-caramel': 'Caramel-coated popcorn',
  'con-popcorn-cheese': 'Cheese-dusted popcorn',
  'con-cola-r': 'A glass of cola over ice',
  'con-cola-l': 'A large soft drink in a paper cup',
  'con-lassi': 'A tall glass of sweet lassi',
  'con-lemon-soda': 'A glass of lemon soda with fresh lime',
  'con-tea': 'A cup of masala tea',
  'con-samosa': 'Fried vegetable samosas',
  'con-chicken-roll': 'A chicken roll in a paratha wrap',
  'con-nachos': 'Corn chips with warm cheese sauce',
  'con-mishti': 'An assortment of Bengali sweets',
  'con-choc-icecream': 'A serving of chocolate ice cream',
  'con-combo-two': 'Popcorn and drinks for two',
  'con-combo-family': 'A sharing spread of cinema snacks',
};

const rows = photos.map((p) => ({ ...p, alt: ALT[p.itemId] ?? `${p.slug} from the counter` }));

const seen = new Map();
for (const row of rows) {
  if (seen.has(row.sourceFile)) throw new Error(`duplicate photo: ${row.itemId} / ${seen.get(row.sourceFile)}`);
  seen.set(row.sourceFile, row.itemId);
}

const body = rows
  .map(
    (r) => `  {
    itemId: '${r.itemId}',
    basePath: '${r.basePath}',
    widths: [${r.widths.join(', ')}],
    alt: '${esc(r.alt)}',
    creator: '${esc(r.creator)}',
    provider: '${esc(r.provider)}',
    licence: '${esc(r.licence)}',
    licenceUrl: '${esc(r.licenceUrl)}',
    sourcePage: '${esc(r.sourcePage)}',
    originalDimensions: '${r.originalWidth}×${r.originalHeight}',
    downloadedAt: '${r.downloadedAt}',
  },`,
  )
  .join('\n');

writeFileSync(
  'src/data/concessionMedia.ts',
  `/**
 * Counter photography.
 *
 * Every item on the counter has its own real photograph, downloaded once from a
 * commercially-licensed source and committed to this repository under
 * \`public/media/concessions/\`. No item shares a photograph with another, and
 * the running application never requests an image from a remote host.
 *
 * Full attribution, licence and download date for each file is in
 * \`docs/concession-image-sources.md\`.
 *
 * Generated by \`scripts/build-concession-media.mjs\`.
 */

export interface ConcessionPhoto {
  itemId: string;
  /** Local path without width or extension. */
  basePath: string;
  widths: number[];
  alt: string;
  creator: string;
  provider: string;
  licence: string;
  licenceUrl: string;
  sourcePage: string;
  originalDimensions: string;
  downloadedAt: string;
}

export const concessionPhotos: ConcessionPhoto[] = [
${body}
];

export const concessionPhotoById = new Map(concessionPhotos.map((p) => [p.itemId, p]));
`,
);

const docRows = rows
  .map(
    (r) =>
      `| ${r.itemId} | [${r.title ?? r.slug}](${r.sourcePage}) | ${r.creator} | ${r.provider} | ${r.licence} | ${r.downloadedAt} | \`${r.basePath}-*\` |`,
  )
  .join('\n');

writeFileSync(
  'docs/concession-image-sources.md',
  `# Concession photography — sources and licences

Every photograph on the counter is a real image of real food, downloaded once at
authoring time and committed to this repository. Nothing is fetched at runtime,
nothing is hotlinked, and nothing here was generated.

All images were located through the [Openverse](https://openverse.org) API,
filtered to licences that permit **commercial** reuse. No item reuses another
item's photograph — asserted by \`npm run validate:content\`.

Each file is stored at three widths (480 / 800 / 1200 px) in AVIF, WebP and JPEG,
cropped to 4:3 for the card slot.

| Item | Source | Creator | Provider | Licence | Downloaded | Local files |
|---|---|---|---|---|---|---|
${docRows}

## Licence obligations

- **CC0 / Public Domain** — no attribution required; credited here regardless.
- **CC BY / CC BY-SA** — attribution required. The creator, provider and licence
  are recorded above and in \`src/data/concessionMedia.ts\`, which ships with the
  application.

## Why these images and not stock photography

The brief called for real food photography rather than illustration. Openverse
aggregates Wikimedia Commons, Rawpixel, StockSnap and Flickr under filterable
licences, needs no API key, and gives a verifiable source page for every file —
which is what makes the attribution above checkable rather than decorative.
`,
);

console.log(`wrote src/data/concessionMedia.ts and docs/concession-image-sources.md (${rows.length} items)`);
